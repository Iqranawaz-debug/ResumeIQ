import ExplainableResults from './ExplainableResults'
import ImprovementReport from './ImprovementReport'
import RequirementMatrix from './RequirementMatrix'
import DocumentChecks from './DocumentChecks'

function PrintableReport({ candidate, analysis, improvements, improvementDraft }) {
  if (!candidate || !analysis) return null

  const hasJobFit = analysis.job_fit_score !== null && analysis.job_fit_score !== undefined

  return (
    <div className="print-report">
      <div className="print-header">
        <div className="print-brand">ResumeIQ</div>
        <span className="print-date">Generated {new Date().toLocaleDateString()}</span>
      </div>

      <div className="print-profile">
        <h1>{candidate.name || 'Candidate'}</h1>
        <p className="print-contact">
          {candidate.email || 'No email found'}
          {candidate.phone ? ` • ${candidate.phone}` : ''}
        </p>
        <span className="print-experience-level">{analysis.experience_level}</span>
      </div>

      <div className="print-score-section">
        <div className="print-score-circle">
          <span className="print-score-number">{analysis.overall_score}</span>
          <span className="print-score-max">/ 100</span>
        </div>
        <div>
          <p className="print-recommendation">{analysis.recommendation}</p>
          {hasJobFit && (
            <p className="print-score-detail">
              Resume Quality: {analysis.resume_quality_score}% &middot; Job Fit: {analysis.job_fit_score}%
              {analysis.job_fit_label ? ` (${analysis.job_fit_label})` : ''}
            </p>
          )}
          {analysis.job_fit_method === 'ai' && Number.isFinite(analysis.local_overall_score) && (
            <p className="print-score-detail">AI-assisted score. Local rules score for comparison: {analysis.local_overall_score} / 100 (job fit {analysis.local_job_fit_score}).</p>
          )}
        </div>
      </div>

      {analysis.explanation?.requirement_lines && (
        <div className="print-section">
          <h2>Requirement review</h2>
          <RequirementMatrix lines={analysis.explanation.requirement_lines} aiEvidence={analysis.ai_match_evidence} />
        </div>
      )}

      {candidate.skills_by_category && (
        <div className="print-section">
          <h2>Skills</h2>
          <div className="print-skills">
            {Object.entries(candidate.skills_by_category).map(([category, skills]) => (
              <p key={category} className="print-skill-group">
                <strong>{category}:</strong> {skills.join(', ')}
              </p>
            ))}
          </div>
        </div>
      )}

      <div className="print-columns">
        <div className="print-section">
          <h2>Strengths</h2>
          <ul>
            {analysis.strengths.map((item, i) => (
              <li key={i}>{item}</li>
            ))}
          </ul>
        </div>
        <div className="print-section">
          <h2>Weaknesses</h2>
          <ul>
            {(analysis.weaknesses || []).map((item, i) => (
              <li key={i}>{item}</li>
            ))}
          </ul>
        </div>
      </div>

      <div className="print-section print-recommendation-box">
        <h2>Recommendation</h2>
        <p className="print-recommendation-text">{analysis.recommendation}</p>
        <ul>
          {analysis.suggestions.map((item, i) => (
            <li key={i}>{item}</li>
          ))}
        </ul>
      </div>

      <div className="print-section">
        <h2>Suggested Interview Questions</h2>
        <ol>
          {(analysis.interview_questions || []).map((item, i) => (
            <li key={i}>{item}</li>
          ))}
        </ol>
      </div>

      <ExplainableResults explanation={analysis.explanation} expandLimitations />
      <DocumentChecks checks={candidate.document_checks} />
      <ImprovementReport data={improvements} draft={improvementDraft} />
      <p className="print-footer">Generated by ResumeIQ — advisory document review, subject to human verification</p>
    </div>
  )
}

export default PrintableReport
